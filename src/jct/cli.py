"""Command-line interface for JCT semantic code search."""

from __future__ import annotations

import argparse
import contextlib
import sys
from pathlib import Path
from typing import Any

from colorama import Fore, init

from jct.demo import index_folder, index_zip
from jct.json_output import write_json_response
from jct.search import (
    reciprocal_rank_fusion,
    reformulate_query,
    search,
    search_with_reformulation,
)
from jct.terminal import (
    display_banner,
    display_error,
    display_help,
    display_main_menu,
    display_no_results,
    display_original_query,
    display_reformulated_queries,
    display_result_details,
    display_results_menu,
    display_results_table,
    display_search_progress,
    display_search_strategy_menu,
    display_source_info,
    display_source_menu,
    display_success,
    display_warning,
)

init(autoreset=True)


# ---------------------------------------------------------------------------
# Argument parsing
# ---------------------------------------------------------------------------

def build_parser() -> argparse.ArgumentParser:
    """Create the command-line argument parser."""
    parser = argparse.ArgumentParser(
        prog="jct",
        description="JCT: Semantic Python Code Search",
    )

    subparsers = parser.add_subparsers(dest="command")

    setup_parser = subparsers.add_parser(
        "setup",
        help="Index a Python project",
    )
    setup_parser.add_argument(
        "--path",
        type=str,
        default=".",
        help="Path to the Python project",
    )
    setup_parser.add_argument(
        "--no-cache",
        action="store_true",
        help="Disable indexing cache",
    )

    search_parser = subparsers.add_parser(
        "search",
        help="Search Python code semantically",
    )
    search_parser.add_argument(
        "query",
        type=str,
        nargs="?",
        help="Natural-language description of the code",
    )
    search_parser.add_argument(
        "--path",
        type=str,
        default=".",
        help="Python project directory or ZIP archive",
    )
    search_parser.add_argument(
        "--top-k",
        type=int,
        default=5,
        help="Maximum number of results to display",
    )
    search_parser.add_argument(
        "--min-score",
        type=float,
        default=0.5,
        help="Minimum similarity score",
    )
    search_parser.add_argument(
        "--no-query-expansion",
        action="store_true",
        help="Disable query expansion",
    )
    search_parser.add_argument(
        "--no-typo-correction",
        action="store_true",
        help="Disable typo correction",
    )
    search_parser.add_argument(
        "--no-query-reformulation",
        action="store_true",
        help="Disable interactive query reformulation",
    )
    search_parser.add_argument(
        "--no-cache",
        action="store_true",
        help="Disable indexing cache",
    )
    search_parser.add_argument(
        "--no-llm",
        action="store_true",
        help="Disable AI-generated fallback results",
    )
    search_parser.add_argument(
        "--json",
        action="store_true",
        help="Output results as JSON",
    )

    return parser


# ---------------------------------------------------------------------------
# AI fallback
# ---------------------------------------------------------------------------

def run_fallback(query: str, no_llm: bool = False) -> int:
    """Offer an AI-generated fallback when semantic search finds no results."""
    if no_llm:
        display_warning(
            "No relevant code was found. AI fallback is disabled."
        )
        return 1

    try:
        from jct.llm_runtime import generate_fallback
    except ImportError:
        display_warning(
            "No relevant code was found, and the AI fallback is unavailable."
        )
        return 1

    try:
        answer = generate_fallback(query)

        if not answer:
            display_warning("The AI fallback did not return a result.")
            return 1

        print()
        print(Fore.YELLOW + "AI-GENERATED, UNVERIFIED" + Fore.RESET)
        print(
            "This response was generated by AI and was not retrieved "
            "from your project or ZIP archive."
        )
        print("-" * 65)
        print(answer)
        print("-" * 65)
        return 0

    except Exception as exc:
        display_warning(f"AI fallback failed: {exc}")
        return 1


# ---------------------------------------------------------------------------
# Query selection
# ---------------------------------------------------------------------------

def _choose_search_query(
    original_query: str,
    interactive: bool = True,
) -> tuple[str, str]:
    """
    Select the query strategy.

    Returns:
        (query_text, strategy), where strategy is single, automatic,
        manual, or cancel.
    """
    if not interactive:
        return original_query, "single"

    display_original_query(original_query)

    try:
        alternatives = reformulate_query(original_query)
    except Exception as exc:
        display_warning(f"Could not generate query suggestions: {exc}")
        alternatives = []

    if not alternatives:
        display_warning(
            "No alternative queries were generated. "
            "Searching with the original query."
        )
        return original_query, "single"

    display_reformulated_queries(alternatives)
    display_search_strategy_menu()

    while True:
        choice = input("\nChoose [0/A/M/B]: ").strip().lower()

        if choice in {"0", "o", "original"}:
            return original_query, "single"

        if choice in {"a", "automatic"}:
            return original_query, "automatic"

        if choice in {"b", "back", "cancel"}:
            return original_query, "cancel"

        if choice == "m" or choice == "manual":
            print("\nChoose suggestions by number, separated by commas.")
            print("Enter 0 to search only the original query.")

            for index, alternative in enumerate(alternatives, start=1):
                print(f"  {index}. {alternative}")

            original_option = len(alternatives) + 1
            print(f"  {original_option}. Original query")

            selection = input("\nYour selection: ").strip()

            if not selection:
                display_warning("No selection made.")
                continue

            try:
                selected_numbers = [
                    int(value.strip())
                    for value in selection.split(",")
                    if value.strip()
                ]
            except ValueError:
                display_error(
                    "Enter valid numbers separated by commas."
                )
                continue

            if not selected_numbers:
                display_warning("No valid selections were entered.")
                continue

            if 0 in selected_numbers:
                if len(selected_numbers) != 1:
                    display_error(
                        "Choose 0 by itself to search only the original query."
                    )
                    continue

                return original_query, "single"

            invalid_numbers = [
                number
                for number in selected_numbers
                if number < 1 or number > original_option
            ]

            if invalid_numbers:
                display_error(
                    f"Invalid selection(s): {invalid_numbers}."
                )
                continue

            selected_queries: list[str] = []

            if original_option in selected_numbers:
                selected_queries.append(original_query)

            for number in selected_numbers:
                if 1 <= number <= len(alternatives):
                    selected_queries.append(alternatives[number - 1])

            selected_queries = list(dict.fromkeys(selected_queries))

            if not selected_queries:
                display_warning(
                    "No valid queries were selected. Try again."
                )
                continue

            if len(selected_queries) == 1:
                return selected_queries[0], "single"

            return "\n".join(selected_queries), "manual"

        display_error("Choose 0, A, M, or B.")


# ---------------------------------------------------------------------------
# Search execution
# ---------------------------------------------------------------------------

def _search_selected_queries(
    query_text: str,
    chunks: list[dict[str, Any]],
    embeddings: Any,
    top_k: int = 5,
    min_score: float = 0.5,
    strategy: str = "single",
    use_query_expansion: bool = True,
    use_typo_correction: bool = True,
) -> list[dict[str, Any]]:
    """Execute the requested search strategy."""
    options = {
        "top_k": top_k,
        "min_score": min_score,
        "use_query_expansion": use_query_expansion,
        "use_typo_correction": use_typo_correction,
    }

    if strategy == "automatic":
        return search_with_reformulation(
            query_text,
            chunks,
            embeddings,
            **options,
        )

    if strategy == "manual":
        queries = list(
            dict.fromkeys(
                line.strip()
                for line in query_text.splitlines()
                if line.strip()
            )
        )

        ranked_lists = [
            search(query, chunks, embeddings, **options)
            for query in queries
        ]

        nonempty_lists = [
            ranked_list for ranked_list in ranked_lists if ranked_list
        ]

        if not nonempty_lists:
            return []

        return reciprocal_rank_fusion(
            nonempty_lists,
            top_k=top_k,
        )

    return search(
        query_text,
        chunks,
        embeddings,
        **options,
    )


# ---------------------------------------------------------------------------
# Result display
# ---------------------------------------------------------------------------

def _print_results(
    results: list[dict[str, Any]],
    query: str | None = None,
) -> None:
    """Display ranked search results."""
    if results:
        display_results_table(results, query=query)


def _show_result_details(
    results: list[dict[str, Any]],
) -> None:
    """Allow the user to inspect individual results."""
    if not results:
        display_warning("There are no results to inspect.")
        return

    while True:
        choice = input(
            f"\nEnter a result number [1-{len(results)}], "
            "or press Enter to return to WHAT NEXT: "
        ).strip()

        if not choice or choice.lower() in {"b", "back"}:
            return

        if choice.lower() in {"q", "quit", "exit"}:
            return

        try:
            index = int(choice)
        except ValueError:
            display_error("Please enter a valid result number.")
            continue

        if not 1 <= index <= len(results):
            display_error(
                f"Enter a number between 1 and {len(results)}."
            )
            continue

        display_result_details(results[index - 1], rank=index)


def _display_next_menu(has_results: bool) -> None:
    """Display the appropriate WHAT NEXT menu."""
    if has_results:
        display_results_menu()
        return

    print("\nWHAT NEXT?")
    print("  2  Search again")
    print("  3  Change the similarity threshold")
    print("  4  Choose another project")
    print("  5  Return to the main menu")
    print("  Q  Quit")


# ---------------------------------------------------------------------------
# Source indexing
# ---------------------------------------------------------------------------

def _load_source(
    path: Path,
    no_cache: bool = False,
) -> tuple[list[dict[str, Any]], Any]:
    """Index a selected folder or ZIP archive."""
    display_source_info(path)

    try:
        with display_search_progress("Indexing Python files...") as progress:
            task = progress.add_task(
                "Indexing Python files...",
                total=None,
            )

            if path.is_file() and path.suffix.lower() == ".zip":
                chunks, embeddings = index_zip(
                    str(path),
                    use_cache=not no_cache,
                )
            elif path.is_dir():
                chunks, embeddings = index_folder(
                    str(path),
                    use_cache=not no_cache,
                )
            else:
                display_error(
                    "Select a Python project directory or ZIP archive."
                )
                return [], None

            progress.update(
                task,
                description="Indexing complete",
                completed=1,
                total=1,
            )

    except Exception as exc:
        display_error(f"Failed to index source: {exc}")
        return [], None

    if not chunks:
        display_warning("No Python code chunks were found in this source.")
    else:
        display_success(f"Indexed {len(chunks)} code chunks.")

    return chunks, embeddings


# ---------------------------------------------------------------------------
# Non-interactive search command
# ---------------------------------------------------------------------------

def run_search(args: argparse.Namespace) -> int:
    """Execute the traditional command-line search workflow."""
    query = getattr(args, "query", None)
    path = Path(getattr(args, "path", ".")).expanduser()

    if not query or not query.strip():
        display_error("Please provide a search query.")
        return 2

    if not path.exists():
        display_error(f"Path does not exist: {path}")
        return 2

    top_k = getattr(args, "top_k", 5)
    min_score = getattr(args, "min_score", 0.5)
    no_cache = getattr(args, "no_cache", False)
    no_llm = getattr(args, "no_llm", False)
    json_mode = getattr(args, "json", False)

    use_query_expansion = not getattr(
        args,
        "no_query_expansion",
        False,
    )
    use_typo_correction = not getattr(
        args,
        "no_typo_correction",
        False,
    )

    disable_reformulation = getattr(
        args,
        "no_query_reformulation",
        False,
    )

    # Only prompt for query reformulation when interactive input is available.
    interactive_terminal = sys.stdin.isatty() and sys.stdout.isatty()

    output_context = (
        contextlib.redirect_stdout(sys.stderr)
        if json_mode
        else contextlib.nullcontext()
    )

    with output_context:
        try:
            if path.is_file() and path.suffix.lower() == ".zip":
                chunks, embeddings = index_zip(
                    path,
                    use_cache=not no_cache,
                )
            elif path.is_dir():
                chunks, embeddings = index_folder(
                    path,
                    use_cache=not no_cache,
                )
            else:
                display_error(
                    "The source must be a project directory or ZIP archive."
                )
                return 2

        except Exception as exc:
            display_error(f"Failed to index source: {exc}")
            return 1

        if not chunks:
            if json_mode:
                write_json_response(query=query, results=[])
                return 1

            display_warning("No Python code chunks were found.")

            if no_llm:
                return 1

            return run_fallback(query)

        if not json_mode:
            display_source_info(path)

        try:
            if not disable_reformulation and not json_mode and interactive_terminal:
                selected_query, strategy = _choose_search_query(
                    query,
                    interactive=True,
                )

                if strategy == "cancel":
                    return 0

                results = _search_selected_queries(
                    selected_query,
                    chunks,
                    embeddings,
                    top_k=top_k,
                    min_score=min_score,
                    strategy=strategy,
                    use_query_expansion=use_query_expansion,
                    use_typo_correction=use_typo_correction,
                )
            else:
                results = search(
                    query,
                    chunks,
                    embeddings,
                    top_k=top_k,
                    min_score=min_score,
                    use_query_expansion=use_query_expansion,
                    use_typo_correction=use_typo_correction,
                )

        except Exception as exc:
            display_error(f"Search failed: {exc}")

            if json_mode:
                write_json_response(query=query, results=[])

            return 1

        if json_mode:
            write_json_response(query=query, results=results)
            return 0 if results else 1

        if results:
            _print_results(results, query=query)
            return 0

        display_no_results(query, min_score)

        if no_llm:
            display_warning(
                "AI fallback is disabled. Try a different query "
                "or lower the minimum score."
            )
            return 1

        return run_fallback(query)


# ---------------------------------------------------------------------------
# Setup command
# ---------------------------------------------------------------------------

def run_setup(args: argparse.Namespace) -> int:
    """Index a Python project."""
    path = Path(getattr(args, "path", ".")).expanduser()
    no_cache = getattr(args, "no_cache", False)

    if not path.exists():
        display_error(f"Path does not exist: {path}")
        return 2

    if not path.is_dir():
        display_error("The setup path must be a Python project directory.")
        return 2

    try:
        chunks, _embeddings = index_folder(
            str(path),
            use_cache=not no_cache,
        )
    except Exception as exc:
        display_error(f"Failed to index project: {exc}")
        return 1

    if not chunks:
        display_warning("No Python code chunks were found.")
        return 1

    display_success(
        f"Successfully indexed {len(chunks)} code chunks from {path}."
    )
    return 0


# ---------------------------------------------------------------------------
# Interactive source selection
# ---------------------------------------------------------------------------

def _choose_source(
    required_kind: str | None = None,
) -> Path | None:
    """Ask the user to select a project directory or ZIP archive."""
    while True:
        display_source_menu()

        if required_kind == "folder":
            print("\nChoose option 1 or 2 for a project folder.")
        elif required_kind == "zip":
            print("\nChoose option 3 for a ZIP archive.")

        choice = input("\nEnter your choice [1-3/B]: ").strip().lower()

        if choice in {"b", "back", "q", "quit"}:
            return None

        if choice == "1":
            if required_kind == "zip":
                display_warning("Please choose a ZIP archive.")
                continue

            return Path.cwd()

        if choice == "2":
            if required_kind == "zip":
                display_warning("Please choose a ZIP archive.")
                continue

            path_text = input(
                "Enter the Python project directory path: "
            ).strip().strip('"')

            if not path_text:
                display_warning("Please enter a directory path.")
                continue

            path = Path(path_text).expanduser()

            if not path.exists():
                display_error(f"Path does not exist: {path}")
                continue

            if not path.is_dir():
                display_error("That path is not a directory.")
                continue

            return path

        if choice == "3":
            if required_kind == "folder":
                display_warning("Please choose a project directory.")
                continue

            path_text = input(
                "Enter the ZIP archive path: "
            ).strip().strip('"')

            if not path_text:
                display_warning("Please enter a ZIP file path.")
                continue

            path = Path(path_text).expanduser()

            if not path.exists():
                display_error(f"Path does not exist: {path}")
                continue

            if not path.is_file() or path.suffix.lower() != ".zip":
                display_error("Please select a valid .zip file.")
                continue

            return path

        display_error("Please enter 1, 2, 3, or B.")


# ---------------------------------------------------------------------------
# Interactive search session
# ---------------------------------------------------------------------------

def _interactive_search(
    chunks: list[dict[str, Any]],
    embeddings: Any,
    source_path: Path,
    no_llm: bool = False,
) -> str:
    """
    Run searches against an already-indexed source.

    Returns:
        'search' to search again,
        'source' to choose another source,
        'menu' to return to the main menu,
        or 'quit' to exit.
    """
    min_score = 0.5

    while True:
        print()
        query = input(
            "Describe the code you want to find "
            "(or type 'q' to quit): "
        ).strip()

        if query.lower() in {"q", "quit", "exit"}:
            return "quit"

        if not query:
            display_warning("Please enter a search query.")
            continue

        selected_query, strategy = _choose_search_query(query)

        if strategy == "cancel":
            continue

        try:
            with display_search_progress() as progress:
                task = progress.add_task(
                    "Searching Python code...",
                    total=None,
                )

                results = _search_selected_queries(
                    selected_query,
                    chunks,
                    embeddings,
                    top_k=5,
                    min_score=min_score,
                    strategy=strategy,
                )

                progress.update(
                    task,
                    description="Search complete",
                    completed=1,
                    total=1,
                )

        except Exception as exc:
            display_error(f"Search failed: {exc}")
            continue

        if results:
            _print_results(results, query=query)
        else:
            display_no_results(query, min_score)

            if not no_llm:
                answer = input(
                    "\nWould you like an AI-generated fallback? [y/N]: "
                ).strip().lower()

                if answer in {"y", "yes"}:
                    run_fallback(selected_query)

        # Keep the current query active until the user chooses Search again.
        while True:
            _display_next_menu(has_results=bool(results))

            choice = input(
                "\nChoose an option [1-5/Q]: "
            ).strip().lower()

            # Option 1: View a result.
            if choice == "1":
                if not results:
                    display_warning("There are no results to inspect.")
                    continue

                _show_result_details(results)
                continue

            # Option 2: Search again.
            if choice == "2":
                break

            # Option 3: Change threshold and rerun the current query.
            if choice == "3":
                try:
                    new_threshold = float(
                        input(
                            "Enter the minimum similarity score (0-1): "
                        ).strip()
                    )
                except ValueError:
                    display_error("Enter a number between 0 and 1.")
                    continue

                if not 0.0 <= new_threshold <= 1.0:
                    display_error(
                        "The threshold must be between 0 and 1."
                    )
                    continue

                min_score = new_threshold

                try:
                    results = _search_selected_queries(
                        selected_query,
                        chunks,
                        embeddings,
                        top_k=5,
                        min_score=min_score,
                        strategy=strategy,
                    )
                except Exception as exc:
                    display_error(f"Search failed: {exc}")
                    continue

                if results:
                    _print_results(results, query=query)
                else:
                    display_no_results(query, min_score)

                # Loop back to WHAT NEXT using the updated results.
                continue

            # Option 4: Choose another project.
            if choice == "4":
                return "source"

            # Option 5: Return to the main menu.
            if choice == "5":
                return "menu"

            # Q: Quit the application.
            if choice in {"q", "quit", "exit"}:
                return "quit"

            display_warning("Please choose a valid option.")

        # Option 2 was selected. Return to the query prompt.
        continue


# ---------------------------------------------------------------------------
# Main interactive application
# ---------------------------------------------------------------------------

def run_interactive() -> int:
    """Launch the interactive JCT application."""
    display_banner()

    while True:
        display_main_menu()
        choice = input("\nEnter your choice [1-5/Q]: ").strip().lower()

        if choice in {"q", "quit", "exit"}:
            display_success("Goodbye!")
            return 0

        # Option 4: Help.
        if choice == "4":
            display_help()
            continue

        # Option 5: Settings information.
        if choice == "5":
            display_warning(
                "Search settings currently use the default top 5 results "
                "and minimum similarity score of 0.5."
            )
            continue

        # Select the initial source.
        if choice == "3":
            source_path = _choose_source()
        elif choice == "1":
            source_path = _choose_source(required_kind="folder")
        elif choice == "2":
            source_path = _choose_source(required_kind="zip")
        else:
            display_error("Please enter 1, 2, 3, 4, 5, or Q.")
            continue

        if source_path is None:
            continue

        # Keep the selected source until the user chooses another source
        # or returns to the main menu.
        while True:
            chunks, embeddings = _load_source(source_path)

            if not chunks:
                break

            action = _interactive_search(
                chunks,
                embeddings,
                source_path,
            )

            if action == "search":
                continue

            if action == "source":
                new_source = _choose_source()

                if new_source is None:
                    break

                source_path = new_source
                continue

            if action == "menu":
                break

            if action == "quit":
                display_success("Goodbye!")
                return 0

            break


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main() -> int:
    """Run JCT from the command line."""
    if len(sys.argv) == 1:
        return run_interactive()

    parser = build_parser()
    args = parser.parse_args()

    if args.command == "setup":
        return run_setup(args)

    if args.command == "search":
        return run_search(args)

    parser.print_help()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
