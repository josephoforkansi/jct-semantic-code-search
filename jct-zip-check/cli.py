
"""Command-line interface for JCT semantic code search."""

import argparse
from pathlib import Path

from colorama import Fore, init

from jct.demo import index_folder, index_zip
from jct.search import search

init(autoreset=True)


def build_parser() -> argparse.ArgumentParser:
    """Build the JCT command-line argument parser."""
    parser = argparse.ArgumentParser(
        prog="jct",
        description="Search Python code by meaning and behavioral intent.",
    )

    subparsers = parser.add_subparsers(dest="command")

    subparsers.add_parser(
        "setup",
        help="Install JCT's managed Ollama runtime and Llama model.",
    )

    search_parser = subparsers.add_parser(
        "search",
        help="Search a Python project or ZIP archive.",
    )

    search_parser.add_argument(
        "query",
        help="Describe the code you want to find.",
    )
    search_parser.add_argument(
        "--path",
        default=".",
        help="Project directory or ZIP archive (default: current directory).",
    )
    search_parser.add_argument(
        "--top-k",
        type=int,
        default=5,
        help="Maximum number of results (default: 5).",
    )
    search_parser.add_argument(
        "--min-score",
        type=float,
        default=0.5,
        help="Minimum relevance score (default: 0.5).",
    )
    search_parser.add_argument(
        "--no-query-expansion",
        action="store_true",
        help="Disable query expansion.",
    )
    search_parser.add_argument(
        "--no-typo-correction",
        action="store_true",
        help="Disable typo correction.",
    )
    search_parser.add_argument(
        "--no-cache",
        action="store_true",
        help="Rebuild the index instead of using a saved cache.",
    )
    search_parser.add_argument(
        "--no-llm",
        action="store_true",
        help="Disable Llama fallback for this search.",
    )

    return parser


def run_setup() -> int:
    """Install JCT's private Ollama runtime and model."""
    from jct.llm_runtime import setup_model

    try:
        setup_model()
    except Exception as exc:
        print(Fore.RED + f"JCT Llama setup failed: {exc}")
        return 1

    return 0


def run_fallback(query: str) -> int:
    """Ask Llama for help when JCT cannot find relevant code."""
    from jct.llm_runtime import generate_fallback

    print(Fore.YELLOW + "\nNo relevant code was found in the archive.")
    print(Fore.CYAN + "JCT is asking its Llama assistant for help...\n")

    try:
        answer = generate_fallback(query)
    except Exception as exc:
        print(Fore.RED + f"JCT's Llama assistant could not respond: {exc}")
        print(
            Fore.YELLOW
            + "Run `uv run jct setup` and try again, "
            + "or search with `--no-llm`."
        )
        return 1

    print(Fore.MAGENTA + "JCT AI ASSISTANT — GENERATED RESPONSE\n")
    print(answer)
    print(
        Fore.YELLOW
        + "\nNote: This response was generated by AI. "
        + "It was not retrieved from your project or archive."
    )

    return 0


def run_search(args: argparse.Namespace) -> int:
    """Index the source, search it, and optionally invoke Llama."""
    if args.top_k <= 0:
        print(Fore.RED + "Error: --top-k must be greater than zero.")
        return 2

    if not 0.0 <= args.min_score <= 1.0:
        print(Fore.RED + "Error: --min-score must be between 0 and 1.")
        return 2

    source_path = Path(args.path).expanduser()

    if not source_path.exists():
        print(Fore.RED + f"Error: source path does not exist: {source_path}")
        return 2

    if source_path.is_file() and source_path.suffix.lower() == ".zip":
        chunks, embeddings = index_zip(
            source_path,
            use_cache=not args.no_cache,
        )
    elif source_path.is_dir():
        chunks, embeddings = index_folder(
            source_path,
            use_cache=not args.no_cache,
        )
    else:
        print(
            Fore.RED
            + "Error: --path must be a directory or a ZIP archive."
        )
        return 2

    print(Fore.CYAN + f"\nQuery: {args.query}")
    print(Fore.CYAN + f"Source: {source_path.resolve()}")

    if not chunks:
        print(Fore.YELLOW + "No searchable Python code was found.")
        if args.no_llm:
            return 1
        return run_fallback(args.query)

    results = search(
        args.query,
        chunks,
        embeddings,
        top_k=args.top_k,
        min_score=args.min_score,
        use_query_expansion=not args.no_query_expansion,
        use_typo_correction=not args.no_typo_correction,
    )

    if not results:
        print(Fore.YELLOW + "No results met the relevance threshold.")
        if args.no_llm:
            return 0
        return run_fallback(args.query)

    print(Fore.GREEN + f"\nTop {len(results)} results:\n")

    for rank, result in enumerate(results, start=1):
        print(
            Fore.CYAN
            + f"{rank}. Score: {result['score']:.3f} | "
            + f"{result['file']}:{result['start_line']} | "
            + f"{result['type'].capitalize()} {result['name']}"
        )

        code = result.get("code", "")
        snippet = code[:500]
        if len(code) > 500:
            snippet += "\n..."

        print(Fore.WHITE + snippet)

        docstring = result.get("docstring", "")
        if docstring:
            print(Fore.MAGENTA + f"Docstring: {docstring[:200]}")

        print("-" * 60)

    return 0


def main() -> None:
    """Run the JCT CLI."""
    parser = build_parser()
    args = parser.parse_args()

    if args.command == "setup":
        raise SystemExit(run_setup())

    if args.command == "search":
        raise SystemExit(run_search(args))

    parser.print_help()


if __name__ == "__main__":
    main()
